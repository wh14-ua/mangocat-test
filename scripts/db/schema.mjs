#!/usr/bin/env node
// Order database schema checks (see schema-tools.mjs for why).
//
//   node scripts/db/schema.mjs verify                 migrations.lock.json + generated schema are up to date (CI)
//   node scripts/db/schema.mjs lock                   record new migrations in the lock (never rewrites old ones)
//   node scripts/db/schema.mjs generate               regenerate workers/shang-hai-orders/src/schema.generated.ts
//   node scripts/db/schema.mjs check --local [--persist-to DIR] [--repair]
//                                                     compare a local D1 (wrangler dev state) with the migrations;
//                                                     --repair adds what is missing (backup first, data untouched)
//   node scripts/db/schema.mjs check --remote         read-only comparison of the deployed D1 (needs wrangler login)
//
// Exit codes: 0 ok, 1 drift / lock problem, 2 could not check.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  describeDrift,
  diffSchema,
  expectedSchema,
  hasDrift,
  INTROSPECT_SQL,
  migrationHash,
  readMigrationFiles,
  repairPlan,
  requiredShape,
  schemaFromRows,
  verifyLock,
} from "./schema-tools.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const WORKER_DIR = join(ROOT, "workers/shang-hai-orders");
export const MIGRATIONS_DIR = join(WORKER_DIR, "migrations");
export const LOCK_FILE = join(WORKER_DIR, "migrations.lock.json");
export const GENERATED_FILE = join(WORKER_DIR, "src/schema.generated.ts");
const DATABASE = "shang-hai-orders";

export function readLock() {
  return existsSync(LOCK_FILE) ? JSON.parse(readFileSync(LOCK_FILE, "utf8")) : { migrations: {} };
}

export function generatedSource(migrationsDir = MIGRATIONS_DIR) {
  const shape = requiredShape(expectedSchema(migrationsDir));
  return `// GENERATED by \`npm run db:generate\` from workers/shang-hai-orders/migrations/*.sql — do not edit.
// The Worker refuses to serve (503 schema-outdated) when the database lacks any of these, instead
// of failing later with "D1_ERROR: no such column". Kept in sync by the test suite.
export const REQUIRED_SCHEMA = ${JSON.stringify(shape, null, 2)} as const;
`;
}

function wrangler(args, { input } = {}) {
  return spawnSync("npx", ["--no-install", "wrangler", ...args], {
    cwd: WORKER_DIR,
    encoding: "utf8",
    input,
    env: { ...process.env, CI: "1", WRANGLER_SEND_METRICS: "false", FORCE_COLOR: "0" },
    maxBuffer: 64 * 1024 * 1024,
  });
}

function parseWranglerJson(stdout) {
  const start = stdout.indexOf("[");
  if (start === -1) throw new Error(`unexpected wrangler output: ${stdout.slice(0, 300)}`);
  return JSON.parse(stdout.slice(start));
}

/**
 * Rows of an introspection (or any read-only query) against a local or remote D1.
 * @param {string} sql
 * @param {{ remote?: boolean, persistTo?: string }} [options]
 * @returns {Record<string, unknown>[]}
 */
export function queryD1(sql, { remote = false, persistTo = undefined } = {}) {
  const target = remote ? ["--remote"] : ["--local", ...(persistTo ? ["--persist-to", persistTo] : [])];
  const res = wrangler(["d1", "execute", DATABASE, ...target, "--json", "--command", sql.replace(/\s+/g, " ")]);
  if (res.status !== 0) throw new Error(`wrangler d1 execute failed:\n${res.stderr || res.stdout}`);
  const out = parseWranglerJson(res.stdout);
  return out.flatMap((r) => r.results ?? []);
}

/** Backs up a local wrangler state dir's D1 files (before any repair). */
function backupLocalD1(persistTo) {
  const d1 = join(persistTo, "v3", "d1");
  if (!existsSync(d1)) return null;
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const target = join(persistTo, "backups", stamp, "d1");
  mkdirSync(dirname(target), { recursive: true });
  cpSync(d1, target, { recursive: true });
  return target;
}

/**
 * Compares a local D1 with the migrations and, with `repair`, applies the additive repair.
 * Used by `npm run demo:local` before the Worker starts.
 */
/**
 * @param {{ persistTo?: string, repair?: boolean, log?: (message: string) => void }} [options]
 * @returns {{ ok: boolean, drift: object, repaired: boolean, problems?: string[], blocked?: string[], error?: string, backup?: string | null, statements?: string[] }}
 */
export function checkLocalDatabase({ persistTo = undefined, repair = false, log = console.log } = {}) {
  const expected = expectedSchema(MIGRATIONS_DIR);
  const actual = schemaFromRows(queryD1(INTROSPECT_SQL, { persistTo }));
  const drift = diffSchema(expected, actual);
  if (!hasDrift(drift)) return { ok: true, drift, repaired: false };
  const problems = describeDrift(drift);
  if (!repair) return { ok: false, drift, problems, repaired: false };

  const plan = repairPlan(expected, drift);
  if (plan.blocked.length) return { ok: false, drift, problems, blocked: plan.blocked, repaired: false };
  const backup = persistTo ? backupLocalD1(persistTo) : null;
  const file = join(persistTo ?? WORKER_DIR, `schema-repair-${Date.now()}.sql`);
  writeFileSync(file, plan.statements.join("\n") + "\n");
  log(`Repairing the local database (backup: ${backup ? relative(ROOT, backup) : "none"}):\n  ${plan.statements.join("\n  ")}`);
  const res = wrangler(["d1", "execute", DATABASE, "--local", ...(persistTo ? ["--persist-to", persistTo] : []), "--file", file]);
  if (res.status !== 0) return { ok: false, drift, problems, error: res.stderr || res.stdout, backup, repaired: false };
  const after = diffSchema(expected, schemaFromRows(queryD1(INTROSPECT_SQL, { persistTo })));
  return { ok: !hasDrift(after), drift: after, problems, statements: plan.statements, backup, repaired: true };
}

function verify() {
  const problems = verifyLock(readMigrationFiles(MIGRATIONS_DIR), readLock()).map((p) => p.message);
  const current = existsSync(GENERATED_FILE) ? readFileSync(GENERATED_FILE, "utf8") : "";
  if (current !== generatedSource()) problems.push("src/schema.generated.ts is out of date (run: npm run db:generate)");
  if (problems.length) {
    console.error(`Schema verification FAILED:\n  - ${problems.join("\n  - ")}`);
    return 1;
  }
  console.log(`Schema verification OK: ${Object.keys(readLock().migrations).length} migrations locked, generated schema up to date.`);
  return 0;
}

function lock() {
  const files = readMigrationFiles(MIGRATIONS_DIR);
  const current = readLock();
  const modified = verifyLock(files, current).filter((p) => p.kind !== "unlocked");
  if (modified.length) {
    console.error(`Refusing to update the lock:\n  - ${modified.map((p) => p.message).join("\n  - ")}`);
    return 1;
  }
  const migrations = { ...current.migrations };
  for (const [name, text] of Object.entries(files)) migrations[name] ??= migrationHash(text);
  const next = {
    _comment:
      "SHA-256 of every migration (LF line endings). Never edit a migration listed here: databases that applied it would not get the change. Add a new migration and run `npm run db:lock`.",
    migrations,
  };
  writeFileSync(LOCK_FILE, `${JSON.stringify(next, null, 2)}\n`);
  console.log(`Locked ${Object.keys(migrations).length} migrations.`);
  return 0;
}

function check(argv) {
  const remote = argv.includes("--remote");
  const repair = argv.includes("--repair");
  const at = argv.indexOf("--persist-to");
  const persistTo = at !== -1 ? resolve(argv[at + 1]) : undefined;
  if (remote && repair) {
    console.error("--repair is only for local test databases. For a deployed database, write a new migration.");
    return 2;
  }
  try {
    if (remote) {
      const drift = diffSchema(expectedSchema(MIGRATIONS_DIR), schemaFromRows(queryD1(INTROSPECT_SQL, { remote: true })));
      if (!hasDrift(drift)) {
        console.log("Remote database schema matches the migrations.");
        return 0;
      }
      console.error(`Remote database schema DIFFERS from the migrations:\n  - ${describeDrift(drift).join("\n  - ")}`);
      return 1;
    }
    const result = checkLocalDatabase({ persistTo, repair });
    if (result.ok) {
      console.log(result.repaired ? "Local database repaired: schema now matches the migrations." : "Local database schema matches the migrations.");
      return 0;
    }
    console.error(`Local database schema DIFFERS from the migrations:\n  - ${(result.problems ?? describeDrift(result.drift)).join("\n  - ")}`);
    if (result.blocked?.length) console.error(`Cannot repair automatically:\n  - ${result.blocked.join("\n  - ")}`);
    if (result.error) console.error(result.error);
    if (!repair) console.error("Repair it (backup first, data kept): add --repair. Or start a clean local state.");
    return 1;
  } catch (error) {
    console.error(`Could not check the schema: ${error instanceof Error ? error.message : error}`);
    return 2;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, ...argv] = process.argv.slice(2);
  const commands = {
    verify,
    lock,
    generate: () => {
      writeFileSync(GENERATED_FILE, generatedSource());
      console.log(`Wrote ${relative(ROOT, GENERATED_FILE)}`);
      return 0;
    },
    check: () => check(argv),
  };
  if (!commands[command]) {
    console.error("usage: schema.mjs verify | lock | generate | check (--local [--persist-to DIR] [--repair] | --remote)");
    process.exit(2);
  }
  process.exit(commands[command]());
}
