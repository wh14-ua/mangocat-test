#!/usr/bin/env node
/**
 * Builds the staff panel client into panel/generated/assets.ts (committed), which the
 * Worker inlines into the /admin page under a per-request CSP nonce.
 *
 *   npm run build:panel                 type-check panel/client, bundle JS + CSS, embed icons
 *   npm run build:panel -- --icons      first redraw the PNG icons with ImageMagick (`convert`)
 *   npm run build:panel -- --check      only verify that generated/assets.ts is up to date
 *
 * The bundle is deterministic (same sources + same esbuild = same bytes); the panel test
 * rebuilds it in memory and compares.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as esbuild from "esbuild";

const PANEL_DIR = dirname(fileURLToPath(import.meta.url));
const WORKER_DIR = dirname(PANEL_DIR);
export const GENERATED_PATH = join(PANEL_DIR, "generated", "assets.ts");
const ICON_DIR = join(PANEL_DIR, "icons");

/** Phones from the last few years: <dialog>, :focus-visible, dvh, CSS inset. */
const TARGETS = ["es2020", "chrome100", "safari15.4", "firefox100", "edge100"];

/** Exported constant name -> PNG file in panel/icons. */
export const ICONS = {
  ICON_192_PNG: "icon-192.png",
  ICON_512_PNG: "icon-512.png",
  APPLE_TOUCH_ICON_PNG: "apple-touch-icon.png",
};

const FORBIDDEN_IN_BUNDLE = [/\binnerHTML\b/, /\bouterHTML\b/, /\binsertAdjacentHTML\b/, /\bdocument\.write(ln)?\b/, /\beval\(/, /\bnew Function\(/];

/** Type-checks panel/client with DOM types (the Worker's tsconfig has none). Throws on errors. */
export function typecheckClient({ quiet = false } = {}) {
  const tsc = join(WORKER_DIR, "node_modules", "typescript", "bin", "tsc");
  try {
    execFileSync(process.execPath, [tsc, "-p", join(PANEL_DIR, "client", "tsconfig.json")], { cwd: WORKER_DIR, encoding: "utf8", stdio: quiet ? "pipe" : ["ignore", "inherit", "inherit"] });
  } catch (error) {
    const output = `${error.stdout ?? ""}${error.stderr ?? ""}`.trim();
    throw new Error(`panel/client does not type-check${output ? `:\n${output}` : ""}`);
  }
}

export async function bundleClient() {
  const common = { bundle: true, minify: true, write: false, target: TARGETS, charset: "utf8", legalComments: "none", logLevel: "silent", absWorkingDir: WORKER_DIR };
  const [js, css] = await Promise.all([
    esbuild.build({ ...common, entryPoints: [join(PANEL_DIR, "client", "main.ts")], format: "iife", platform: "browser" }),
    esbuild.build({ ...common, entryPoints: [join(PANEL_DIR, "client", "styles.css")] }),
  ]);
  return { js: js.outputFiles[0].text.trim(), css: css.outputFiles[0].text.trim() };
}

/** Both strings are inlined in <script>/<style>: they must not be able to close those tags. */
export function assertInlineSafe({ js, css }) {
  if (/<\/script/i.test(js) || /<!--/.test(js)) throw new Error("The JS bundle contains </script or <!--");
  if (/<\/style/i.test(css)) throw new Error("The CSS bundle contains </style");
  for (const pattern of FORBIDDEN_IN_BUNDLE) {
    if (pattern.test(js)) throw new Error(`The JS bundle uses a forbidden API: ${pattern}`);
  }
}

export function readIcons() {
  return Object.fromEntries(Object.entries(ICONS).map(([name, file]) => [name, readFileSync(join(ICON_DIR, file)).toString("base64")]));
}

export function renderModule({ js, css, icons }) {
  const hash = createHash("sha256");
  for (const part of [js, css, ...Object.values(icons)]) hash.update(part).update("\0");
  return [
    "// GENERATED by panel/build.mjs from panel/client and panel/icons. Do not edit by hand:",
    "// run `npm run build:panel` in workers/shang-hai-orders (tests fail when this is stale).",
    `export const PANEL_BUILD = ${JSON.stringify(hash.digest("hex").slice(0, 16))};`,
    `export const PANEL_JS = ${JSON.stringify(js)};`,
    `export const PANEL_CSS = ${JSON.stringify(css)};`,
    ...Object.entries(icons).map(([name, base64]) => `export const ${name} = ${JSON.stringify(base64)};`),
    "",
  ].join("\n");
}

/** The exact contents generated/assets.ts must have for the current sources. */
export async function expectedModule() {
  const bundle = await bundleClient();
  assertInlineSafe(bundle);
  return renderModule({ ...bundle, icons: readIcons() });
}

/**
 * The app icon: the restaurant's 上海 seal, white on lacquer red, framed like a chop.
 * Drawn at 1024 px and reduced, full-bleed so it also works as a maskable icon (the frame
 * stays inside the 80 % safe circle).
 */
export function drawIcons() {
  const work = mkdtempSync(join(tmpdir(), "shp-icons-"));
  try {
    const master = join(work, "icon-1024.png");
    execFileSync("convert", [
      "-size", "1024x1024", "xc:#A7342F",
      "-fill", "none", "-stroke", "#FFFFFF", "-strokewidth", "22",
      "-draw", "roundrectangle 322,170 702,854 36,36",
      "-stroke", "none", "-fill", "#FFFFFF", "-font", "Noto-Serif-CJK-SC-Black", "-gravity", "center",
      "-pointsize", "286", "-annotate", "+0-174", "上", "-annotate", "+0+150", "海",
      master,
    ]);
    mkdirSync(ICON_DIR, { recursive: true });
    for (const [file, size] of [["icon-512.png", 512], ["icon-192.png", 192], ["apple-touch-icon.png", 180]]) {
      execFileSync("convert", [
        master, "-filter", "Lanczos", "-resize", `${size}x${size}`, "-depth", "8", "+dither", "-colors", "64", "-strip",
        "-define", "png:exclude-chunks=date,time", join(ICON_DIR, file),
      ]);
    }
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

async function main(args) {
  if (args.has("--icons")) drawIcons();
  if (!args.has("--no-typecheck")) typecheckClient();
  const source = await expectedModule();
  if (args.has("--check")) {
    let current = "";
    try {
      current = readFileSync(GENERATED_PATH, "utf8");
    } catch {
      /* missing */
    }
    if (current !== source) {
      console.error("panel/generated/assets.ts is out of date: run `npm run build:panel`.");
      process.exit(1);
    }
    console.log("panel/generated/assets.ts is up to date.");
    return;
  }
  mkdirSync(dirname(GENERATED_PATH), { recursive: true });
  writeFileSync(GENERATED_PATH, source);
  const size = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`;
  const { js, css } = await bundleClient();
  console.log(`panel built: JS ${size(js)}, CSS ${size(css)} -> ${GENERATED_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    await main(new Set(process.argv.slice(2)));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
